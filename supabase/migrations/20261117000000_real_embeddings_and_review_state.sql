-- ============================================================
-- P0: Replace the fabricated 1536-dim character-hash "embeddings"
--     with real 768-dim Gemini embeddings.
-- P1: Persist flashcard review state so spaced repetition works.
-- ============================================================

-- ------------------------------------------------------------
-- 1. document_chunks: retype the vector column to 768 dims
-- ------------------------------------------------------------
-- Every existing vector in this column was produced by a character
-- histogram, not an embedding model. Similarities computed from them are
-- meaningless (all components are non-negative, so cosine is always >= 0
-- and the 0.2 threshold admits nearly everything).
--
-- They cannot be cast to a different dimension, and they carry no value,
-- so they are dropped. `content` is untouched: the derived data is
-- regenerated by the re-embed backfill, nothing authored is lost.
--
-- The matching RPC is dropped first because its parameter type is
-- VECTOR(1536) and CREATE OR REPLACE cannot change a parameter type.
DROP FUNCTION IF EXISTS public.match_document_chunks(VECTOR, FLOAT, INT, UUID, UUID);

ALTER TABLE public.document_chunks
  ALTER COLUMN embedding TYPE VECTOR(768) USING NULL::vector(768);

-- Provenance for each vector, so a model swap can be detected and the
-- stale rows targeted instead of silently mixing embedding spaces.
ALTER TABLE public.document_chunks
  ADD COLUMN IF NOT EXISTS embedding_model TEXT,
  ADD COLUMN IF NOT EXISTS embedded_at TIMESTAMPTZ;

COMMENT ON COLUMN public.document_chunks.embedding IS
  '768-dim Gemini embedding. NULL means not yet embedded — such rows are excluded from similarity search.';
COMMENT ON COLUMN public.document_chunks.page_number IS
  'Real page number when the source carried page boundaries; NULL when the source is plain text.';

ALTER TABLE public.document_chunks
  ALTER COLUMN page_number DROP DEFAULT;

-- ------------------------------------------------------------
-- 2. Recreate the similarity search RPC at the new dimension
-- ------------------------------------------------------------
CREATE OR REPLACE FUNCTION match_document_chunks (
  query_embedding VECTOR(768),
  match_threshold FLOAT,
  match_count INT,
  p_user_id UUID,
  p_topic_id UUID DEFAULT NULL
)
RETURNS TABLE (
  id UUID,
  document_name TEXT,
  page_number INT,
  content TEXT,
  similarity FLOAT
)
LANGUAGE plpgsql
AS $$
BEGIN
  RETURN QUERY
  SELECT
    dc.id,
    dc.document_name,
    dc.page_number,
    dc.content,
    1 - (dc.embedding <=> query_embedding) AS similarity
  FROM public.document_chunks dc
  WHERE dc.user_id = p_user_id
    AND (p_topic_id IS NULL OR dc.topic_id = p_topic_id)
    -- Rows without a real vector must never be returned: their distance is
    -- undefined and they would be cited as if they matched.
    AND dc.embedding IS NOT NULL
    AND 1 - (dc.embedding <=> query_embedding) > match_threshold
  ORDER BY dc.embedding <=> query_embedding
  LIMIT match_count;
END;
$$;

-- Approximate nearest-neighbour index for cosine distance. Built after the
-- retype above so it indexes the 768-dim column.
CREATE INDEX IF NOT EXISTS document_chunks_embedding_idx
  ON public.document_chunks
  USING hnsw (embedding vector_cosine_ops);

-- ------------------------------------------------------------
-- 3. flashcards: persist the review schedule
-- ------------------------------------------------------------
-- `box` and `next_review_at` have always existed but were never written by
-- any code path, so every card stayed permanently due and reviews were
-- counted in client state only. These columns record what actually happened.
ALTER TABLE public.flashcards
  ADD COLUMN IF NOT EXISTS last_reviewed_at TIMESTAMPTZ,
  ADD COLUMN IF NOT EXISTS review_count INTEGER NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS lapses INTEGER NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS ease NUMERIC(4, 2) NOT NULL DEFAULT 2.5;

DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'flashcards_ease_range') THEN
    ALTER TABLE public.flashcards
      ADD CONSTRAINT flashcards_ease_range CHECK (ease >= 1.3 AND ease <= 5.0);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'flashcards_box_range') THEN
    ALTER TABLE public.flashcards
      ADD CONSTRAINT flashcards_box_range CHECK (box BETWEEN 1 AND 5);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'flashcards_counts_non_negative') THEN
    ALTER TABLE public.flashcards
      ADD CONSTRAINT flashcards_counts_non_negative CHECK (review_count >= 0 AND lapses >= 0);
  END IF;
END $$;

-- The due-today queue filters by owner and time on every dashboard load.
CREATE INDEX IF NOT EXISTS flashcards_user_next_review_idx
  ON public.flashcards (user_id, next_review_at);
